package com.intruphon.app.data.media

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class TrackMetadataBuilderTest {
    @Test fun topicChannelAndRepeatedArtist() {
        val m = buildTrackMetadata("X_X (super slowed) — Ilyhiryu", "Ilyhiryu - Topic", null, 2024, "https://x", null)
        assertEquals("X_X (super slowed)", m.title)
        assertEquals("Ilyhiryu", m.artist)
        assertEquals(2024, m.year)
        assertNull(m.album)
    }

    @Test fun artistPrefixInTitle() {
        val m = buildTrackMetadata("Daft Punk - One More Time", "Daft Punk", null, null, null, null)
        assertEquals("One More Time", m.title)
    }

    @Test fun albumAndYearFromAutoGeneratedDescription() {
        val description = "Provided to YouTube by Some Label\n\nSong Name · Artist One · Artist Two\n\nThe Album Title\n\n℗ 2019 Some Label\n\nReleased on: 2019-05-17\n"
        val m = buildTrackMetadata("Song Name", "Artist One - Topic", description, 2024, null, null)
        assertEquals("The Album Title", m.album)
        assertEquals(2019, m.year)
    }

    @Test fun ordinaryDescriptionIsIgnored() {
        val m = buildTrackMetadata("My video", "Some Channel", "Thanks for watching\n\nReleased on: 1999", 2021, null, null)
        assertNull(m.album)
        assertEquals(2021, m.year)
        assertEquals("My video", m.title)
    }

    @Test fun missingUploader() {
        val m = buildTrackMetadata("Just a title", null, null, null, null, null)
        assertNull(m.artist)
        assertEquals("Just a title", m.title)
    }
}
